const v = new Uint32Array(32);
const m = new Uint32Array(32);

function add64AA(out: Uint32Array, a: number, b: number): void {
  const o0 = out[a]! + out[b]!;
  let o1 = out[a + 1]! + out[b + 1]!;
  if (o0 >= 0x100000000) o1++;
  out[a] = o0;
  out[a + 1] = o1;
}

function add64AC(out: Uint32Array, a: number, b0: number, b1: number): void {
  let o0 = out[a]! + b0;
  if (b0 < 0) o0 += 0x100000000;
  let o1 = out[a + 1]! + b1;
  if (o0 >= 0x100000000) o1++;
  out[a] = o0;
  out[a + 1] = o1;
}

function get32(arr: Uint8Array, i: number): number {
  return arr[i]! ^ (arr[i + 1]! << 8) ^ (arr[i + 2]! << 16) ^ (arr[i + 3]! << 24);
}

function g(a: number, b: number, c: number, d: number, ix: number, iy: number): void {
  const x0 = m[ix]!, x1 = m[ix + 1]!, y0 = m[iy]!, y1 = m[iy + 1]!;

  add64AA(v, a, b);
  add64AC(v, a, x0, x1);

  let xor0 = v[d]! ^ v[a]!;
  let xor1 = v[d + 1]! ^ v[a + 1]!;
  v[d] = xor1;
  v[d + 1] = xor0;

  add64AA(v, c, d);

  xor0 = v[b]! ^ v[c]!;
  xor1 = v[b + 1]! ^ v[c + 1]!;
  v[b] = (xor0 >>> 24) ^ (xor1 << 8);
  v[b + 1] = (xor1 >>> 24) ^ (xor0 << 8);

  add64AA(v, a, b);
  add64AC(v, a, y0, y1);

  xor0 = v[d]! ^ v[a]!;
  xor1 = v[d + 1]! ^ v[a + 1]!;
  v[d] = (xor0 >>> 16) ^ (xor1 << 16);
  v[d + 1] = (xor1 >>> 16) ^ (xor0 << 16);

  add64AA(v, c, d);

  xor0 = v[b]! ^ v[c]!;
  xor1 = v[b + 1]! ^ v[c + 1]!;
  v[b] = (xor1 >>> 31) ^ (xor0 << 1);
  v[b + 1] = (xor0 >>> 31) ^ (xor1 << 1);
}

interface Ctx {
  b: Uint8Array;
  h: Uint32Array;
  t: number;
  c: number;
  outlen: number;
}

function compress(ctx: Ctx, last: boolean): void {
  let i = 0;
  for (i = 0; i < 16; i++) {
    v[i] = ctx.h[i]!;
    v[i + 16] = IV[i]!;
  }
  v[24] = v[24]! ^ ctx.t;
  v[25] = v[25]! ^ (ctx.t / 0x100000000);
  if (last) {
    v[28] = ~v[28]!;
    v[29] = ~v[29]!;
  }
  for (i = 0; i < 32; i++) m[i] = get32(ctx.b, 4 * i);

  for (i = 0; i < 12; i++) {
    const s = SIGMA.slice(i * 16, i * 16 + 16);
    g(0, 8, 16, 24, s[0]!, s[1]!);
    g(2, 10, 18, 26, s[2]!, s[3]!);
    g(4, 12, 20, 28, s[4]!, s[5]!);
    g(6, 14, 22, 30, s[6]!, s[7]!);
    g(0, 10, 20, 30, s[8]!, s[9]!);
    g(2, 12, 22, 24, s[10]!, s[11]!);
    g(4, 14, 16, 26, s[12]!, s[13]!);
    g(6, 8, 18, 28, s[14]!, s[15]!);
  }
  for (i = 0; i < 16; i++) ctx.h[i] = ctx.h[i]! ^ v[i]! ^ v[i + 16]!;
}

/** `outlen` goes in the parameter block. That is the whole point of this file. */
function init(outlen: number): Ctx {
  const ctx: Ctx = {
    b: new Uint8Array(128),
    h: new Uint32Array(16),
    t: 0,
    c: 0,
    outlen,
  };
  for (let i = 0; i < 16; i++) ctx.h[i] = IV[i]!;
  ctx.h[0] = ctx.h[0]! ^ 0x01010000 ^ outlen;
  return ctx;
}

function update(ctx: Ctx, input: Uint8Array): void {
  for (let i = 0; i < input.length; i++) {
    if (ctx.c === 128) {
      ctx.t += ctx.c;
      compress(ctx, false);
      ctx.c = 0;
    }
    ctx.b[ctx.c++] = input[i]!;
  }
}

function final(ctx: Ctx): Uint8Array {
  ctx.t += ctx.c;
  while (ctx.c < 128) ctx.b[ctx.c++] = 0;
  compress(ctx, true);
  const out = new Uint8Array(ctx.outlen);
  for (let i = 0; i < ctx.outlen; i++) {
    out[i] = ctx.h[i >> 2]! >> (8 * (i & 3));
  }
  return out;
}

const HEX = "0123456789abcdef";

function hex(bytes: Uint8Array): string {
  let s = "";
  for (const b of bytes) s += HEX[b >> 4]! + HEX[b & 15]!;
  return s;
}

export function blake2bHex(text: string, outlen: number): string {
  const ctx = init(outlen);
  update(ctx, new TextEncoder().encode(text));
  return hex(final(ctx));
}

/** `schema.make_id`: the parts joined by NUL, hashed at eight bytes. */
export function makeId(...parts: string[]): string {
  return blake2bHex(parts.join("\u0000"), 8);
}

/** `schema.call_site_id`. The ordinal is the only discriminator that is not a position. */
export function callSiteId(callerId: string, calleeExpr: string, ordinal: number): string {
  return makeId("site", callerId, calleeExpr, String(ordinal));
}

/** `schema.control_point_id`. */
export function controlPointId(
  routineId: string,
  kind: string,
  header: string,
  ordinal: number,
): string {
  return makeId("control", routineId, kind, header, String(ordinal));
}

/** `schema.hash_source`: sixteen bytes, not eight. */
export function hashSource(text: string): string {
  return blake2bHex(text, 16);
}
