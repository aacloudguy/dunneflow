/**
 * The identity functions, reproduced on this side of the pipe — and the one place in this
 * plugin that is a **second implementation of something the host already has**.
 *
 * `schema.make_id` hashes `parts.join("\0")` with BLAKE2b at a digest size of 8, and every
 * id in a map is derived from it. There is no way to avoid writing it twice: a routine's
 * id has to exist before the facts leave this process, and the host cannot recompute it
 * without the names it was built from. Rule 51 says move a rule to where every caller
 * passes; a process boundary is the one place that cannot be done — so the rule is
 * instead pinned by a **shared fixture**, `tests/fixtures/ids/vectors.json`, generated by
 * `schema.make_id` and asserted from both sides.
 *
 * **`crypto.createHash("blake2b512", { outputLength: 8 })` is wrong twice**, and it is what
 * `PLAN-v2.md` said to write. Node's OpenSSL refuses it outright —
 * `not XOF or invalid length` — and if it did not, it would still be the wrong hash:
 * BLAKE2b puts the digest length **into its parameter block**, so an 8-byte digest is not
 * the first 8 bytes of a 64-byte one. Measured: `blake2b(b"ab")[:8]` is `b32c0573d242b3a9`
 * and `blake2b(b"ab", digest_size=8)` is `0e52b5f187de1088`. A plugin that shipped the
 * truncation would mint ids that look exactly like ids and match nothing in the map.
 *
 * So BLAKE2b is implemented here, from RFC 7693, in the usual two-32-bit-words-per-lane
 * form because JavaScript has no 64-bit integer arithmetic that is fast.
 */

const IV = new Uint32Array([
  0xf3bcc908, 0x6a09e667, 0x84caa73b, 0xbb67ae85,
  0xfe94f82b, 0x3c6ef372, 0x5f1d36f1, 0xa54ff53a,
  0xade682d1, 0x510e527f, 0x2b3e6c1f, 0x9b05688c,
  0xfb41bd6b, 0x1f83d9ab, 0x137e2179, 0x5be0cd19,
]);

