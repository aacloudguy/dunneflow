"""Ways in, as the dashboard serves them: what each one *is*, and what it starts.

A way in is not a package and not a module. It is **the way the outside world starts this
program** -- a name you can type, a request that arrives, or a module you can run -- paired
with the routines it lands on. `resolve/flows.py` finds them; this says what they are.

**Two questions the cover could not answer, and Tom asked both.**

*"Are these packages, modules, or applications?"* Mensores' fourteen are four different
kinds under two different authorities: four **declared executables** read out of
`pyproject.toml [project.scripts]`, one **HTTP route** started by a request, and nine
**guesses** -- a module-level function DunneFlow recognised by its name, or a `__main__`
guard. The cover drew all fourteen as a name, a kind tag and a bar, and `ways_in()` had
computed the evidence and thrown it away before the wire. Five of those rows are literally
called `main`. So `evidence` travels now, verbatim and unparsed: it is generated by this
tool's own extractor and it *is* the answer, and parsing it into a tidier field would
promote a sentence to a contract for no gain (rule 30).

*"When I click on them and select Code, I would expect to see the file."* For a way in that
starts one routine, that already worked. For `mensores` it could not: the name means
`mensores.cli:app`, which is a **Typer object** -- not a routine, with no file to open -- and
it expands to **107 commands across 44 files**. Clicking selected all 107 and the pane opened
whichever the query returned first: `mensores.cli.examples.list_cmd` from one query,
`mensores/cli/_root.py` from another. Not wrong so much as arbitrary, and unexplained.

So a way in with an `app_id` is a **command tree**, and `describe` returns the tree: the
sub-applications mounted on it and the commands hung off it, each one an ordinary selection.
A tree is not one of the things it holds (rule 74), and which of the two a way in is arrives
as a declared field rather than as `len(roots) > 1` -- "this is a tree" and "this happens to
start several routines" are different facts that look identical on the wire (rule 30).

**Where it lives is answered or refused, never invented.** A single-routine way in has a
file and a line, so it carries them. A command tree's *name* has no definition site at all;
what it has is the file the app object is assembled in, which `cli_mounts` records. When
neither is available the field is `None` and the pane says how many files the thing spans
instead -- a position invented to fill a column is rule 1's defect with a link on it.
"""

from __future__ import annotations

import json
from typing import Any

from ..resolve.flows import app_command_routines, ways_in
from ..store import Store


def _routines(store: Store, ids: list[str]) -> dict[str, dict[str, Any]]:
    """The defining site of each routine, keyed by id. Empty ids are dropped, not faked."""
    real = [i for i in dict.fromkeys(ids) if i]
    if not real:
        return {}
    return {
        str(r["id"]): {
            "id": str(r["id"]), "qualname": str(r["qualname"]),
            "module": str(r["module"] or ""), "file": str(r["file"] or ""),
            "line": int(r["line_start"] or 0),
        }
        for r in store.query(
            "SELECT id, qualname, module, file, line_start FROM routines"
            " WHERE id IN (SELECT value FROM json_each(?))",
            (json.dumps(real),),
        )
    }


def _app_site(store: Store, app_id: str) -> dict[str, Any] | None:
    """Where a CLI application object is assembled, from the mounts recorded against it.

    The app object itself is not a routine and has no row in `routines`; `cli_mounts` is the
    only table that records a file for it, because mounting a sub-application is the one act
    that happens *to* it in a file the extractor read. Every mount of one app is written in
    the same place in practice, and the earliest line is taken rather than assumed unique --
    a first mount is a fact, "the file" would be a claim about all of them.
    """
    rows = list(store.query(
        "SELECT file, line FROM cli_mounts WHERE parent_id = ? AND file <> ''"
        " ORDER BY line LIMIT 1", (app_id,)))
    if not rows:
        return None
    return {"file": str(rows[0]["file"]), "line": int(rows[0]["line"] or 0)}


def listing(store: Store) -> list[dict[str, Any]]:
    """Every way in, with what it is and where it lives.

    `ways_in()` ranks them and this answers *what am I looking at* for each. The extra cost
    is two queries per way in over indexed columns on a list that is fourteen long for the
    largest program measured here, paid once at boot with the cover.
    """
    out: list[dict[str, Any]] = []
    for w in ways_in(store):
        roots = list(w["roots"])
        sites = _routines(store, roots)
        files = sorted({s["file"] for s in sites.values() if s["file"]})
        app_id = w.get("app_id")

        # One routine, one place to open. More than one, and the name does not have a
        # definition site -- the app object's assembly point is the nearest true answer,
        # and `None` is the honest one when even that is unrecorded.
        where: dict[str, Any] | None = None
        if len(sites) == 1:
            only = next(iter(sites.values()))
            where = {"file": only["file"], "line": only["line"]} if only["file"] else None
        elif app_id:
            where = _app_site(store, str(app_id))

        out.append({
            "name": w["name"],
            "kind": w["kind"],
            "reach": w["reach"],
            "touches": " ".join(k.value for k in w["kinds"]) or "—",
            "aliases": list(w.get("aliases", [])),
            "nodes": roots,
            # **Declared or guessed**, and the word is the whole point of the row. A console
            # script in `[project.scripts]` is a fact read out of packaging; `run` is a
            # module-level function DunneFlow recognised by its name and nothing more.
            # Drawing them the same way is what made fourteen rows unreadable.
            "declared": bool(w["declared"]),
            # Verbatim, and unparsed on purpose. It is this tool's own sentence and it says
            # exactly what was found -- `pyproject.toml [project.scripts] mensores =
            # mensores.cli:app`, or `conventional name 'run' at module level`.
            "evidence": w["evidence"],
            # **Bound, and why not** -- the third state a way in has (design rule 21).
            # A declared way in whose target this build cannot read is a real front door
            # of the program that this map cannot open, and drawing it with a reach of 0
            # and nothing else says the program has a door that leads nowhere. The
            # sentence comes from `binding_note`, which is also what `anomalies` decides
            # on, so the panel and the worklist cannot disagree (rule 13).
            "bound": bool(w.get("bound", True)),
            "why": str(w.get("why", "")),
            # A command tree, not a routine (rule 30). Declared rather than inferred from
            # the length of `nodes`.
            "app": bool(app_id),
            "app_id": app_id or "",
            "where": where,
            # What it spans, so a tree that cannot name one file says how big it is instead
            # of showing a blank (design rule 21).
            "starts": len(sites),
            "files": len(files),
        })
    return out


def _descendants(store: Store, app_id: str) -> set[str]:
    """Every application mounted under this one, at any depth.

    The set an `inside` id has to be in. Walked rather than asked of the client, and walked
    with `cli_mounts` -- the same table `app_command_routines` recurses through, so what can
    be opened and what was counted are the same tree (rule 13).
    """
    seen: set[str] = set()
    todo = [app_id] if app_id else []
    while todo:
        here = todo.pop()
        for r in store.query(
                "SELECT child_id FROM cli_mounts WHERE parent_id = ? AND child_id IS NOT NULL",
                (here,)):
            child = str(r["child_id"])
            if child not in seen:
                seen.add(child)
                todo.append(child)
    return seen


def _mount_name(store: Store, child_id: str) -> str:
    """The name a sub-application is mounted under -- `quaestor`, not its object id.

    **The earliest mount, taken rather than assumed unique**, which is exactly what
    `_app_site` two functions up already says about the same table: a first mount is a
    fact, and *"the name"* would be a claim about all of them. It was `LIMIT 1` with no
    order at all until 2026-09-18, so an application mounted twice -- `add_typer(inner,
    name="ledger")` and `add_typer(inner, name="books")` -- printed whichever name the
    rows happened to be stored in. Not a list that came back shuffled: a **different
    answer**, which is why a `LIMIT` with no `ORDER BY` is the sharpest form of this
    defect and why `tools/ordering.py --survey` counts one as a finding rather than
    exempting it.

    `file, line` and not `name`: alphabetical would be defended and arbitrary, and the
    order a person wrote them in is the one they can check. The residue is stated rather
    than hidden -- a second mount under a second name is still not shown anywhere, and
    this returns the first of them.
    """
    rows = list(store.query(
        "SELECT name FROM cli_mounts WHERE child_id = ? AND name <> ''"
        " ORDER BY file, line LIMIT 1", (child_id,)))
    return str(rows[0]["name"]) if rows else ""


def describe(store: Store, name: str, inside: str = "") -> dict[str, Any]:
    """One way in, opened: what starts it, and everything it can run.

    The pane behind clicking an application. For a single-routine way in this is the routine
    and the ordinary selection machinery does the rest; for a command tree it is the tree --
    the sub-applications mounted on it and the commands hung directly off it, each carrying
    the routine id that makes it an ordinary selection.

    **Matched on the name the row prints**, because that is what the reader clicked and the
    cover has no other identity for it. A name that matches nothing is answered with
    `found: false` and a sentence, never with an empty tree: an empty tree reads as an
    application with no commands, which is a different and false claim.
    """
    rows = [w for w in listing(store) if w["name"] == name]
    if not rows:
        return {"found": False,
                "reason": f"no way in of this map is called {name!r}"}
    w = dict(rows[0])
    w["found"] = True

    # **Opening a sub-application is the same question one level down**, which is the whole
    # of chasing a command tree: `quaestor` says it holds 34 and a row that states a number
    # nobody can open is a dead end in a pane built to be followed.
    #
    # The id is **verified to be a descendant, never trusted**. It arrives from the page, and
    # an id taken as given would let any app object in the store be rendered under any way
    # in's name -- a pane that is correct in every respect except that its heading is about
    # something else. Refused with a sentence rather than silently falling back to the root,
    # because a fallback that yields a plausible value hides the failure it was written for
    # (rule 49).
    w["inside"] = None
    if inside:
        if inside not in _descendants(store, str(w["app_id"] or "")):
            return {"found": False,
                    "reason": f"{name!r} has no sub-application by that id"}
        # **Every count on the pane is recomputed for the sub-tree**, or the page says
        # `quaestor` and means `mensores`. Left as they were, `starts`, `files` and the
        # remainder read 107, 44 and 73 over a heading naming a group of 34 -- three numbers
        # that are each true of something the reader is not looking at (rule 24: a
        # measurement must measure the thing it names).
        held = [r for r in app_command_routines(store, inside) if r]
        sites = _routines(store, held)
        w["inside"] = {"id": inside, "name": _mount_name(store, inside) or inside}
        w = dict(w, app_id=inside, app=True, nodes=held,
                 starts=len(sites), files=len({s["file"] for s in sites.values() if s["file"]}),
                 where=_app_site(store, inside))
        # `reach` is what the *way in* commands and belongs to the way in. A sub-application
        # has its own, and the honest one is the routines reachable from what it holds --
        # asked here rather than carried down from a parent it is not a measurement of.
        w["reach"] = len(store.reachable_from_many(held)) if held else 0

    commands: list[dict[str, Any]] = []
    groups: list[dict[str, Any]] = []
    entry: list[dict[str, Any]] = []
    held_by: dict[str, set[str]] = {}
    if w["app_id"]:
        app_id = str(w["app_id"])
        # **Where execution begins**, which is a different question from what the tree can
        # run and the one Tom actually asked. `mensores-mcp = mensores.mcp.__main__:main`
        # names a routine; the commands hang off the app object beside it. These are the
        # `grp = ''` children the filter below excludes from the command list, and counting
        # them as *unnamed* would have reported the program's own front door as "a
        # registration idiom DunneFlow followed far enough to count and not far enough to
        # name" -- a limitation confessed where there is none (rule 32).
        first = list(store.query(
            "SELECT name, routine_id FROM entrypoints"
            " WHERE parent_id = ? AND routine_id IS NOT NULL AND grp = ''"
            " ORDER BY name", (app_id,)))
        for site in _routines(store, [str(r["routine_id"]) for r in first]).values():
            entry.append({
                "name": site["qualname"].rsplit(".", 1)[-1], "kind": w["kind"],
                "node": site["id"], "qualname": site["qualname"],
                "file": site["file"], "line": site["line"],
            })
        # **`grp <> ''` keeps the application out of its own command list** (rule 74). `grp`
        # is the schema's own field for *the CLI app object this command attaches to*, and
        # attaching is exactly what makes something a command rather than the declaration of
        # the executable. The console-script row is a child of the app too -- it is how the
        # app is reached -- and without this it listed `demo` as one of `demo`'s commands,
        # which is the tree offering itself as a way into itself. Filtered on the field that
        # means it rather than on the name matching, because a command legitimately named
        # after its executable is a thing programs do (rule 5).
        direct = list(store.query(
            'SELECT name, routine_id, kind, grp FROM entrypoints'
            " WHERE parent_id = ? AND routine_id IS NOT NULL AND grp <> ''"
            ' ORDER BY name', (app_id,)))
        sites = _routines(store, [str(r["routine_id"]) for r in direct])
        for r in direct:
            site = sites.get(str(r["routine_id"]), {})
            commands.append({
                "name": str(r["name"]), "kind": str(r["kind"]),
                "node": str(r["routine_id"]),
                "qualname": site.get("qualname", ""), "file": site.get("file", ""),
                "line": site.get("line", 0),
            })
        for m in store.query(
                'SELECT name, child_id, file, line FROM cli_mounts'
                ' WHERE parent_id = ? AND child_id IS NOT NULL ORDER BY line', (app_id,)):
            # A mounted sub-application is a *group of commands*, so it states how many it
            # holds rather than pretending to be one of them (rule 74).
            #
            # **Counted with `app_command_routines`, which is what `ways_in` counts the whole
            # tree with.** Counting direct children instead read `telemetry 0` for a group
            # that holds nine commands one mount further down -- a group that says it is
            # empty is a branch a reader will not open (rule 13: the number beside a claim
            # has to be the number the claim is about).
            held = [r for r in app_command_routines(store, str(m["child_id"])) if r]
            held_by[str(m["child_id"])] = set(held)
            groups.append({
                "name": str(m["name"] or m["child_id"]),
                "child_id": str(m["child_id"]),
                "file": str(m["file"] or ""), "line": int(m["line"] or 0),
                "commands": len(set(held)),
            })
    else:
        sites = _routines(store, list(w["nodes"]))
        for site in sites.values():
            commands.append({
                "name": site["qualname"].rsplit(".", 1)[-1], "kind": w["kind"],
                "node": site["id"], "qualname": site["qualname"],
                "file": site["file"], "line": site["line"],
            })

    w["commands"] = commands
    w["groups"] = groups
    w["entry"] = entry
    # What is started and named by neither a command listed here nor a group listed here.
    # Design rule 1: a reader told "starts 107" and shown one command and twelve groups is
    # owed the remainder in words rather than left to add it up and find it does not.
    named = {c["node"] for c in commands} | {c["node"] for c in entry}
    for ids in held_by.values():
        named |= ids
    w["unlisted"] = len({n for n in w["nodes"] if n and n not in named})
    return w
