from dunneflow.render.page import Stamp
from dunneflow.resolve.calls import resolve_calls
from dunneflow.resolve.cli import resolve_cli
from dunneflow.resolve.flows import ways_in, ways_in_affected
from dunneflow.store import Store
from dunneflow.walk import analyze_tree
from tests.test_cpp_reader import _WHY, needs_clang

pytestmark = needs_clang

THING_H = """\
#pragma once
#define UFUNCTION(...)
class AThing {
public:
    UFUNCTION(BlueprintCallable)
    int Add(int a, int b);
    UFUNCTION(BlueprintCallable)
    float Add(float a, float b);
    int Add(int a);
    UFUNCTION(BlueprintNativeEvent)
    void OnHit(int x);
    void OnHit_Implementation(int x);
    UFUNCTION(BlueprintImplementableEvent)
    void OnSpawn();
    UFUNCTION(BlueprintCallable)
    virtual int Shape() = 0;
};
class ABox : public AThing {
public:
    int Shape() override { return 4; }
};
// The trap: `Mul(int, int)` is marked and its body is not in this tree; `Mul(int)` is not
// marked and is. By qualname there is exactly one `AThing.Mul`, and a binder by name takes it.
class AMaths {
public:
    UFUNCTION(BlueprintCallable)
    int Mul(int a, int b);
    int Mul(int a);
};
"""

THING_CPP = """\
#include "Thing.h"
int AThing::Add(int a, int b) { return a + b; }
float AThing::Add(float a, float b) { return a + b; }
int AThing::Add(int a) { return a; }
void AThing::OnHit_Implementation(int x) { Add(x, x); }
int AMaths::Mul(int a) { return a; }
"""


def _program(tmp_path: Path, *, preset: bool = True) -> Store:
    if _WHY:
        pytest.skip(_WHY)
    top = tmp_path / "Runtime"
    if preset:  # the Unreal preset's marker, at or above the analysed root
        (top / "Core" / "Public" / "HAL").mkdir(parents=True)
        (top / "Core" / "Public" / "HAL" / "Platform.h").write_text("", encoding="utf-8")
    game = top / "Game"
    game.mkdir(parents=True)
    (game / "Thing.h").write_text(THING_H, encoding="utf-8")
    (game / "Thing.cpp").write_text(THING_CPP, encoding="utf-8")
    store = Store(tmp_path / "g.db")
    analyze_tree(game, store)
    resolve_calls(store)
    resolve_cli(store)
    return store


def _bound(store: Store) -> dict[str, list[tuple[str | None, int | None]]]:
    """Each way in's name -> the (qualname, line) of what it is bound to, sorted."""
    out: dict[str, list[tuple[str | None, int | None]]] = {}
    for r in store.query(
            "SELECT e.name, r.qualname, r.line_start FROM entrypoints e"
            " LEFT JOIN routines r ON r.id = e.routine_id"
            " ORDER BY e.name, r.line_start"):
        out.setdefault(str(r["name"]), []).append((r["qualname"], r["line_start"]))
    return out


def test_two_marked_overloads_are_two_ways_in_each_bound_to_its_own_body(tmp_path: Path) -> None:
    store = _program(tmp_path)
    try:
        assert _bound(store)["Add"] == [("AThing.Add", 2), ("AThing.Add", 3)], \
            "the overloads were one way in, or bound to the unmarked Add(int)"
    finally:
        store.close()


