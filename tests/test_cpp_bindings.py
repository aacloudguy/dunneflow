"""A UFUNCTION is bound to the declaration it marks (chunk 5b, slice H).

`UFUNCTION(BlueprintCallable)` sits on a declaration in a header and the body is in a
`.cpp`. The host bound such a way in by its qualname, which cannot tell overloads apart:
157 of Runtime's were overloads with one id between them, overwriting each other, and a
marked overload whose body is elsewhere was given its unmarked sibling's. The reader
knows the definition by its USR, so it binds them in the edge pass (`SuppliedBinding`);
and where there is no C++ body at all, it says why, in words the Unreal preset states
rather than the reader.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from dunneflow.anomalies import detect
from dunneflow.resolve.calls import resolve_calls
from dunneflow.resolve.cli import resolve_cli
from dunneflow.resolve.flows import ways_in
from dunneflow.store import Store
from dunneflow.walk import analyze_tree
from tests.test_cpp_reader import _WHY, needs_clang

pytestmark = needs_clang

THING_H = """\
#pragma once
#define UFUNCTION(...)
class AThing {
public:
    UFUNCTION(BlueprintCallable)
    int Add(int a, int b);
    UFUNCTION(BlueprintCallable)
    float Add(float a, float b);
    int Add(int a);
    UFUNCTION(BlueprintNativeEvent)
    void OnHit(int x);
    void OnHit_Implementation(int x);
    UFUNCTION(BlueprintImplementableEvent)
    void OnSpawn();
    UFUNCTION(BlueprintCallable)
    virtual int Shape() = 0;
};
class ABox : public AThing {
public:
    int Shape() override { return 4; }
};
// The trap: `Mul(int, int)` is marked and its body is not in this tree; `Mul(int)` is not
// marked and is. By qualname there is exactly one `AThing.Mul`, and a binder by name takes it.
class AMaths {
public:
    UFUNCTION(BlueprintCallable)
    int Mul(int a, int b);
    int Mul(int a);
};
"""

THING_CPP = """\
#include "Thing.h"
int AThing::Add(int a, int b) { return a + b; }
float AThing::Add(float a, float b) { return a + b; }
int AThing::Add(int a) { return a; }
void AThing::OnHit_Implementation(int x) { Add(x, x); }
int AMaths::Mul(int a) { return a; }
"""


def _program(tmp_path: Path, *, preset: bool = True) -> Store:
    if _WHY:
        pytest.skip(_WHY)
    top = tmp_path / "Runtime"
    if preset:  # the Unreal preset's marker, at or above the analysed root
        (top / "Core" / "Public" / "HAL").mkdir(parents=True)
        (top / "Core" / "Public" / "HAL" / "Platform.h").write_text("", encoding="utf-8")
    game = top / "Game"
    game.mkdir(parents=True)
    (game / "Thing.h").write_text(THING_H, encoding="utf-8")
    (game / "Thing.cpp").write_text(THING_CPP, encoding="utf-8")
    store = Store(tmp_path / "g.db")
    analyze_tree(game, store)
    resolve_calls(store)
    resolve_cli(store)
    return store


def _bound(store: Store) -> dict[str, list[tuple[str | None, int | None]]]:
    """Each way in's name -> the (qualname, line) of what it is bound to, sorted."""
    out: dict[str, list[tuple[str | None, int | None]]] = {}
    for r in store.query(
            "SELECT e.name, r.qualname, r.line_start FROM entrypoints e"
            " LEFT JOIN routines r ON r.id = e.routine_id"
            " ORDER BY e.name, r.line_start"):
        out.setdefault(str(r["name"]), []).append((r["qualname"], r["line_start"]))
    return out


def test_two_marked_overloads_are_two_ways_in_each_bound_to_its_own_body(tmp_path: Path) -> None:
    store = _program(tmp_path)
    try:
        assert _bound(store)["Add"] == [("AThing.Add", 2), ("AThing.Add", 3)], \
            "the overloads were one way in, or bound to the unmarked Add(int)"
    finally:
        store.close()


def test_a_marked_overload_whose_body_is_elsewhere_is_not_given_its_sibling_s(
        tmp_path: Path) -> None:
    """By qualname `AMaths.Mul` is unique, so the host's binder took `Mul(int)` for the
    way in on `Mul(int, int)`. By USR there is no definition of the marked one here."""
    store = _program(tmp_path)
    try:
        assert _bound(store)["Mul"] == [(None, None)], "bound to the unmarked overload"
    finally:
        store.close()


def test_a_native_event_is_bound_to_its_implementation(tmp_path: Path) -> None:
    store = _program(tmp_path)
    try:
        assert _bound(store)["OnHit"] == [("AThing.OnHit_Implementation", 5)]
    finally:
        store.close()


def test_an_implementable_event_is_a_way_in_with_its_reason_and_not_a_finding(
        tmp_path: Path) -> None:
    store = _program(tmp_path)
    try:
        assert _bound(store)["OnSpawn"] == [(None, None)]
        row = next(d for d in ways_in(store) if d["name"] == "OnSpawn")
        assert not row["bound"]
        assert "generated by UnrealHeaderTool" in row["why"]
        lost = [a for a in detect(store).items
                if a.kind == "ENTRYPOINT_NO_TARGET" and a.subject == "OnSpawn"]
        assert lost == [], "a way in with a known reason was reported as leading nowhere"
    finally:
        store.close()


def test_a_pure_virtual_way_in_says_who_implements_it(tmp_path: Path) -> None:
    store = _program(tmp_path)
    try:
        row = next(d for d in ways_in(store) if d["name"] == "Shape")
        assert row["why"] == "it is pure virtual, and implemented by 1 overrider in this tree"
    finally:
        store.close()


def test_without_the_preset_a_native_event_is_not_guessed_by_name(tmp_path: Path) -> None:
    """The suffix is UnrealHeaderTool's rule, so it is the preset's: outside Unreal, a
    declaration with no definition stays unbound -- and the host's name binder, which
    would have bound it to *some* `OnHit`, is not asked."""
    store = _program(tmp_path, preset=False)
    try:
        bound = _bound(store)
        assert bound["OnHit"] == [(None, None)]
        assert bound["Add"] == [("AThing.Add", 2), ("AThing.Add", 3)]
    finally:
        store.close()
