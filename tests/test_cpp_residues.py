"""Chunk 5's residues, no longer deferred (chunk 5b, slice I).

Four things the C/C++ reader said wrongly about C, each found on a real tree:
- tmux's callbacks read as dead code (714 of them), because a callback is passed or stored
  and never called by name;
- OpenUSD's 4,545 files missing `pxr/pxr.h` were a count, with no word that CMake generates
  it or what would supply it;
- every call clang could not resolve said *"receiver's type not written down"*, and C has
  no receivers;
- tmux's `compat/strlcat.c` defined a routine named `__builtin___strlcat_chk` on macOS.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from dunneflow.anomalies import detect
from dunneflow.detectors import FRONTIER_WORDS, RulesMissing, _frontier_words, frontier_words
from dunneflow.resolve.calls import resolve_calls
from dunneflow.store import Store
from dunneflow.walk import analyze_tree
from tests.test_cpp_fragments import _read, _tree
from tests.test_cpp_reader import _WHY, needs_clang

CALLBACKS = """\
struct entry { void (*exec)(int); };
void reg(void (*f)(int));
static void handed(int x) { (void)x; }
static void stored(int x) { (void)x; }
static void lonely(int x) { (void)x; }
static void called(int x) { (void)x; }
const struct entry table = { .exec = stored };
int main(void) { reg(handed); called(1); return 0; }
"""


def _dead(tmp_path: Path, files: dict[str, str]) -> list[str]:
    if _WHY:
        pytest.skip(_WHY)
    root = tmp_path / "prog"
    for name, body in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(body, encoding="utf-8")
    store = Store(tmp_path / "g.db")
    try:
        analyze_tree(root, store)
        resolve_calls(store)
        found = [a for a in detect(store).items if a.kind == "DEAD_CODE"]
        return sorted(o.label for a in found for o in a.occurrences)
    finally:
        store.close()


@needs_clang
def test_a_callback_passed_or_stored_is_not_dead_code(tmp_path: Path) -> None:
    dead = _dead(tmp_path, {"cb.c": CALLBACKS})
    assert "lonely" in dead, "the one routine nothing names must still be reported"
    assert "handed" not in dead, "a routine passed to a call is used"
    assert "stored" not in dead, "a routine stored in a table is used"
    assert "reg" not in dead and "called" not in dead


@needs_clang
def test_a_name_followed_by_a_paren_is_a_call_and_not_a_value(tmp_path: Path) -> None:
    """A use is *named, not called*: `inner();` is a call, and recording it as a value too
    would make the table say every called routine is a callback."""
    if _WHY:
        pytest.skip(_WHY)
    root = tmp_path / "prog"
    root.mkdir()
    (root / "c.c").write_text("static void inner(void) {}\n"
                              "static void outer(void) { inner(); }\n"
                              "void reg(void (*f)(void));\n"
                              "int main(void) { reg(outer); return 0; }\n", encoding="utf-8")
    store = Store(tmp_path / "g.db")
    try:
        analyze_tree(root, store)
        used = sorted(str(r["name"]) for r in store.query("SELECT name FROM value_uses"))
    finally:
        store.close()
    assert used == ["outer"], used


@needs_clang
def test_a_generated_header_is_named_once_with_how_to_supply_it(tmp_path: Path) -> None:
    files = _tree(tmp_path, {
        "config.h.in": "#undef HAVE_THING\n",
        "a.c": '#include "config.h"\nint a(void) { return 0; }\n',
        "b.c": '#include "config.h"\nint b(void) { return 0; }\n',
    })
    if _WHY:
        pytest.skip(_WHY)
    from tests.test_cpp_reader import PLUGIN
    assert PLUGIN is not None
    PLUGIN.open(tmp_path, [f for f in files if f.suffix == ".c"])
    try:
        opened = list(PLUGIN.opened_notes)
        list(PLUGIN.extract([f for f in files if f.suffix == ".c"], tmp_path))
        list(PLUGIN.edges())
        said = list(PLUGIN.edges_said)
    finally:
        PLUGIN.close()
    told = [n for n in opened if "not configured" in n]
    assert len(told) == 1, opened
    assert "config.h (from config.h.in)" in told[0] and "compile_commands.json" in told[0]
    assert any("'config.h' file not found -- generated by the build, from config.h.in" in n
               for n in said), said


def test_a_reason_is_worded_in_its_own_language() -> None:
    assert "clang" in frontier_words("cpp", "untyped")
    assert "receiver" not in frontier_words("cpp", "untyped"), "C has no receivers"
    assert "receiver" in frontier_words("rust", "untyped")
    assert frontier_words("go", "untyped") == FRONTIER_WORDS["untyped"]
    assert frontier_words("", "bound") == FRONTIER_WORDS["bound"]


def test_a_sentence_for_a_reason_nobody_sends_is_refused(tmp_path: Path) -> None:
    with pytest.raises(RulesMissing, match="frontier_words"):
        _frontier_words({"untyed": "a typo"}, "cpp", tmp_path / "cpp.yaml")


@needs_clang
def test_a_definition_a_macro_renames_to_a_builtin_keeps_its_written_name(tmp_path: Path) -> None:
    """macOS's `<string.h>` has `#define strlcat(...) __builtin___strlcat_chk(...)`; the
    same shape, spelled out so it holds on every platform."""
    files = _tree(tmp_path, {"s.c": "#define strlcat(d, s, n) __builtin___strlcat_chk(d, s, n, 0)\n"
                                    "unsigned long strlcat(char *d, const char *s, unsigned long n)"
                                    " { (void)d; (void)s; return n; }\n"})
    facts, _, _ = _read(tmp_path, files)
    assert [r.name for r in facts["s.c"].routines] == ["strlcat"]
